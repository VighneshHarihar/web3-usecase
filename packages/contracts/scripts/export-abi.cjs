// Exports ABI + bytecode for the API (so runtime never needs Hardhat).
const fs = require('fs');
const path = require('path');
const out = path.join(__dirname, '..', 'abi');
fs.mkdirSync(out, { recursive: true });
const names = ['LoyaltyEscrow', 'TestRupee'];
let ts = '// Generated by scripts/export-abi.cjs. Do not edit.\n';
for (const n of names) {
  const art = require(path.join(__dirname, '..', 'artifacts', 'contracts', `${n}.sol`, `${n}.json`));
  fs.writeFileSync(path.join(out, `${n}.json`), JSON.stringify({ abi: art.abi, bytecode: art.bytecode }, null, 2));
  ts += `export const ${n}Abi = ${JSON.stringify(art.abi)} as const;\n`;
  ts += `export const ${n}Bytecode = '${art.bytecode}' as const;\n`;
}
fs.writeFileSync(path.join(out, 'index.ts'), ts);
console.log('exported', names.join(', '));
